"""Derive the supplement's copies of four generated tables, so they cannot drift.

Four tables appear in `supplementary.tex` rather than in the ten-page manuscript, and the
supplement needs its own `\\label` for each so that main.tex's hard-coded "Supplementary
Table~S__" pointers resolve to the right item. Keeping a second, hand-edited copy of a
generated table is how two documents come to quote the same quantity differently: rerun the
analysis and the generated file moves while the copy does not.

The copies differ from their sources by the label and nothing else, so they are produced here
by rewriting that one line. Run this after any script that writes one of the sources.

    python3 analysis/s42_sm_tables.py
"""
import os
import re
import sys

import common

TABLES = os.path.join(common.HERE, '..', 'tables')

#: source table -> the label the supplement's copy must carry
PAIRS = {
}

HEADER = ('%% Generated by analysis/s42_sm_tables.py from %s -- do not edit.\n'
          '%% The supplement needs its own label so that main.tex\'s "Supplementary Table"\n'
          '%% pointers resolve; everything else is the source table verbatim.\n')


def main():
    missing, written = [], []
    for src, (dst, label) in sorted(PAIRS.items()):
        sp = os.path.join(TABLES, src)
        if not os.path.exists(sp):
            missing.append(src)
            continue
        body = open(sp).read()
        if not re.search(r'\\label\{[^}]*\}', body):
            missing.append(src + ' (no \\label to rewrite)')
            continue
        out = re.sub(r'\\label\{[^}]*\}', r'\\label{%s}' % label, body, count=1)
        open(os.path.join(TABLES, dst), 'w').write(HEADER % src + out)
        written.append('%s -> %s (%s)' % (src, dst, label))
    for w in written:
        print('wrote', w)
    if missing:
        print('\nMISSING sources, their copies were left alone:', ', '.join(missing))
        print('Run the script that produces each one first; see README.md.')
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
